def to_camel(snake_str):
    if snake_str in ('_id', 'id'):
        return 'id'
    clean_str = snake_str.lstrip('_')
    if not clean_str:
        return snake_str
    components = clean_str.split('_')
    return components[0] + ''.join(x.title() for x in components[1:])


def camelize_dict(data):
    if isinstance(data, dict):
        return {to_camel(k): camelize_dict(v) for k, v in data.items()}
    elif isinstance(data, list):
        return [camelize_dict(item) for item in data]
    return data

class CamelCaseMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request, call_next):
        response = await call_next(request)
        if response.headers.get('content-type') == 'application/json':
            body = b''
            async for chunk in response.body_iterator:
                body += chunk
            try:
                data = json.loads(body)
                camel_data = camelize_dict(data)
                camel_body = json.dumps(camel_data).encode('utf-8')
                return Response(
                    content=camel_body,
                    status_code=response.status_code,
                    media_type='application/json',
                    headers={k: v for k, v in response.headers.items() if k.lower() != 'content-length'}
                )
            except Exception as e:
                return Response(
                    content=body,
                    status_code=response.status_code,
                    media_type='application/json',
                    headers=dict(response.headers)
                )
        return response

