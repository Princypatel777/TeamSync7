def _register_dynamic_routers():
    """Register routers that may not exist yet (generated by subagents)."""
    import importlib, sys

    optional_routers = [
        ("app.api.groups", "router", "/api/groups"),
        ("app.api.proposals", "router", "/api/proposals"),
        ("app.api.student", "router", "/api/student"),
        ("app.api.agile", "router", "/api/agile"),
        ("app.api.supervision", "router", "/api/supervision"),
        ("app.api.faculty", "router", "/api/faculty"),
        ("app.api.collaboration", "router", "/api/collaboration"),
        ("app.api.evaluation", "router", "/api/evaluation"),
        ("app.api.platform", "router", "/api/platform"),
        ("app.api.qa", "router", "/api/qa"),
        ("app.api.reviews", "router", "/api/reviews"),
        ("app.api.releases", "router", "/api/releases"),
        ("app.api.calendar", "router", "/api/calendar"),
        ("app.api.integration", "router", "/api/integration"),
    ]
    for module_path, attr, prefix in optional_routers:
        try:
            mod = importlib.import_module(module_path)
            router = getattr(mod, attr, None)
            if router:
                app.include_router(router)
        except Exception as e:
            print(f"[Router Warning]: Could not load {module_path}: {e}")


